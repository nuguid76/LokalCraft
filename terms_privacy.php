</p>
<p>
Payment status and order status are recorded separately. A successful payment record
does not automatically mean that the physical order has already been completed,
received, or delivered.
</p>
<h3>7. Delivery Options</h3>
<p>
LokalCraft supports Delivery Options such as Meetup, Pickup, Third-Party Delivery,
and Other, depending on the arrangement between the buyer and seller.
</p>
<p>
LokalCraft does not provide its own real-time courier or automated logistics tracking
service. Third-party delivery arrangements are coordinated externally by the buyer
and seller.
</p>
<p>
Users are responsible for confirming the correct meetup location, pickup location,
delivery service, recipient information, date, and time before finalizing an arrangement.
LokalCraft cannot control the performance, availability, delay, loss, or service quality
of an independently selected third-party delivery provider.
</p>
<h3>8. Payment Options</h3>
<p>
Supported Payment Options include QR-based digital payment and Cash, subject to
the selected Delivery Option.
</p>
<ul>
    <li>Cash is available only for applicable Meetup or Pickup arrangements.</li>
    <li>Third-Party Delivery and Other delivery arrangements require the supported QR-based digital payment option.</li>
    <li>Payment status is recorded separately from order fulfillment and completion.</li>
    <li>Users must review the amount and final arrangement before proceeding with payment.</li>
</ul>
<p>
During system evaluation, QR-based digital payment functions operate within
LokalCraft's configured testing environment. Transaction and wallet values used
during evaluation are system records and do not represent withdrawable funds or
production seller payouts.
</p>
<h3>9. Platform Transaction Fee</h3>
<p>
