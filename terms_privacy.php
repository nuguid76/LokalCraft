<h3>5. Request Order and Order Arrangements</h3>
<p>
Submitting a Request Order does not immediately complete or finalize a transaction.
The buyer initially selects the quantity, optional special request, Delivery Option,
and Payment Option before sending the request to the seller.
</p>
<p>
The buyer and seller may then communicate through LokalCraft's integrated chat to
discuss specific details such as customization, exact location, selected delivery
service, date, and time.
</p>
<p>
The seller prepares the final order arrangement based on the discussion. The buyer
must review and confirm the final arrangement before the seller can proceed with
final order acceptance.
</p>
<p>
Users are responsible for reviewing the final price, quantity, Delivery Option,
Payment Option, location, schedule, customization details, and other order information
before confirming an arrangement.
</p>
<h3>6. Order Status</h3>
<p>
LokalCraft may display order statuses including Pending, Accepted, Processing,
