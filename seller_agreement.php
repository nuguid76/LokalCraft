<h2>LokalCraft Seller Agreement</h2>
<p>
This Seller Agreement applies to users who register, apply, or operate as sellers
on LokalCraft. By submitting a seller application and using seller features, you
acknowledge that you have read, understood, and agreed to the responsibilities and
conditions stated below.
</p>
<h3>1. Seller Registration and Verification</h3>
<p>
Seller access is subject to verification and approval by the LokalCraft Administrator.
Submitting a seller application does not automatically grant seller privileges.
</p>
<ul>
    <li>Sellers must provide accurate and complete personal and business information.</li>
    <li>Required identity and business verification documents must be valid, readable, and unaltered.</li>
    <li>Sellers must only submit identification and business documents that belong to them or that they are authorized to use.</li>
    <li>False, forged, edited, misleading, or fraudulent verification documents are prohibited.</li>
    <li>The LokalCraft Administrator may approve or reject seller applications based on the information and documents submitted.</li>
    <li>Sellers are responsible for keeping their business and profile information accurate and up to date.</li>
</ul>
<h3>2. Handcrafted Products and Marketplace Scope</h3>
<p>
LokalCraft is intended to support handcrafted microenterprises and the sale of
handcrafted products.
</p>
<p>
Sellers are responsible for ensuring that the products they list are appropriate
for LokalCraft's marketplace and are accurately represented.
</p>
<ul>
    <li>Products must be authentic and legally owned or authorized for sale by the seller.</li>
    <li>Counterfeit, fraudulent, harmful, prohibited, or illegal products must not be listed.</li>
    <li>Sellers must not intentionally misrepresent mass-produced products as handcrafted products.</li>
    <li>Sellers must ensure that products comply with applicable rules and regulations relevant to their sale.</li>
</ul>
<h3>3. Product Listing Responsibilities</h3>
<p>
Sellers are responsible for the accuracy of all information contained in their
product listings.
</p>
<ul>
    <li>Product names must accurately identify the item being sold.</li>
    <li>Product images must reasonably represent the actual product.</li>
    <li>Descriptions must accurately explain the product, materials, features, condition, and other relevant details.</li>
    <li>Prices must reflect the amount the seller intends to charge before any mutually agreed changes to an order arrangement.</li>
    <li>Product categories must be selected correctly.</li>
    <li>Stock quantities must be kept reasonably accurate and updated.</li>
    <li>Product location and other listing information must not intentionally mislead buyers.</li>
</ul>
<p>
LokalCraft administrators may monitor product listings and may approve, reject,
restrict, archive, or remove listings that violate marketplace requirements or
platform policies.
</p>
<h3>4. Product Quality</h3>
<p>
Sellers remain responsible for the quality, condition, workmanship, and accuracy
of the products they offer.
</p>
<p>
Product images and descriptions should reasonably match the item that will be
provided to the buyer, including agreed customization when applicable.
</p>
<h3>5. Inventory Management</h3>
<p>
Sellers are responsible for maintaining accurate inventory information for their
listed products.
</p>
<p>
A Request Order does not automatically reserve or deduct physical stock. Final
order acceptance is subject to LokalCraft's required stock checks and applicable
platform-fee requirements.
</p>
<p>
Sellers must not knowingly accept an order when they are unable to provide the
agreed quantity or product.
</p>
<h3>6. Costing and Pricing Assistance</h3>
<p>
LokalCraft provides costing and pricing tools to assist sellers in recording and
reviewing information such as materials, labor, overhead, desired profit, total cost,
suggested selling price, break-even information, and estimated profit.
</p>
<p>
The seller remains responsible for reviewing these calculations and determining
the final selling price of the product.
</p>
<p>
LokalCraft's costing and pricing features are decision-support tools and do not
guarantee sales, profit, demand, or business performance.
</p>
<h3>7. AI-Assisted Comparable Product References</h3>
<p>
LokalCraft may analyze product images and listing information to provide
AI-assisted similar-product or comparable-product references.
</p>
<p>
These results are provided only as additional references. They do not automatically
determine, overwrite, or change the seller's product information or final selling price.
</p>
<p>
Similarity between products does not guarantee that the products have the same
materials, workmanship, production cost, quality, demand, or market value.
</p>
<h3>8. Request Orders</h3>
<p>
When a buyer submits a Request Order, the seller may receive information including
the requested quantity, optional special request, selected Delivery Option, and
selected Payment Option.
</p>
<p>
A Request Order is not yet a completed transaction and must not be treated as a
completed sale before the required arrangement and acceptance process has been
finished.
</p>
<h3>9. Buyer-Seller Communication</h3>
<p>
Sellers may use LokalCraft's integrated chat to communicate with buyers regarding
specific transaction details, including:
</p>
<ul>
    <li>Product customization or special requests;</li>
    <li>Exact meetup or pickup location;</li>
    <li>Selected third-party delivery service;</li>
    <li>Date and time;</li>
    <li>Other necessary order-arrangement details.</li>
</ul>
<p>
Sellers must communicate professionally and respectfully. Fraudulent messages,
harassment, threats, spam, deceptive communication, or attempts to misuse the
platform are prohibited.
</p>
<h3>10. Final Order Arrangement</h3>
<p>
The seller is responsible for preparing the final order arrangement after discussing
the necessary details with the buyer.
</p>
<p>
The final arrangement may include the agreed price, Delivery Option, Payment
Option, location, date, time, and additional notes.
</p>
<p>
If the Delivery Option or Payment Option is changed from the buyer's original
request, the change must be based on an agreement between the buyer and seller.
</p>
<p>
The final arrangement must be sent to the buyer for review and confirmation before
the seller proceeds with final acceptance of the order.
</p>
<h3>11. Order Acceptance</h3>
<p>
The seller may accept an order only after the buyer has confirmed the final
arrangement and the system has completed the applicable checks.
</p>
<p>
These checks may include available stock and platform-fee requirements.
The seller must not intentionally attempt to bypass the required LokalCraft order
acceptance process.
</p>
<h3>12. Order Status Management</h3>
<p>
Sellers are responsible for updating orders according to their actual progress using
the applicable LokalCraft order statuses, which may include:
</p>
<ul>
    <li>Pending;</li>
    <li>Accepted;</li>
    <li>Processing;</li>
    <li>Completed;</li>
    <li>Cancelled; and</li>
    <li>Declined.</li>
</ul>
<p>
Sellers must not intentionally mark orders with false or misleading statuses.
Payment status and order status are recorded separately, and a successful payment
does not automatically mean that an order has already been physically fulfilled.
</p>
<h3>13. Delivery Responsibilities</h3>
<p>
Available Delivery Options may include Meetup, Pickup, Third-Party Delivery,
and Other arrangements supported by LokalCraft.
</p>
<p>
Sellers must clearly communicate and confirm applicable fulfillment details with
the buyer before accepting the final arrangement.
</p>
<p>
LokalCraft does not provide its own real-time courier or automated delivery tracking
service. Third-party delivery services are arranged externally by the buyer and seller.
</p>
<p>
Sellers should provide accurate pickup, meetup, or delivery-related information and
should not intentionally misrepresent fulfillment details.
</p>
<h3>14. Payment Options</h3>
<p>
Supported Payment Options may include QR-based digital payment and Cash,
depending on the selected Delivery Option.
</p>
<ul>
    <li>Cash is available only for applicable Meetup or Pickup orders.</li>
    <li>Third-Party Delivery and Other delivery arrangements require the supported QR-based digital payment option.</li>
    <li>Sellers must not falsely claim that a payment has been completed when LokalCraft does not show the applicable successful payment status.</li>
</ul>
<h3>15. Five Percent (5%) Platform Transaction Fee</h3>
<p>
Sellers acknowledge that LokalCraft records a five percent (5%) platform
transaction fee for applicable successful transactions.
</p>
<p>
For supported QR-based digital transactions, LokalCraft records the corresponding
seller share and platform fee after the payment process is successfully confirmed by
the system.
</p>
<p>
For Cash on Meetup or Pickup orders, the system requires sufficient seller internal
wallet balance to secure the applicable 5% platform fee before the buyer-confirmed
order can be accepted.
</p>
<p>
A seller may therefore be prevented from accepting a Cash on Meetup or Pickup
order when the required platform-fee balance is insufficient.
</p>
<h3>16. Internal Seller Wallet and Transaction Records</h3>
<p>
LokalCraft may maintain internal records showing seller earnings, platform-fee
deductions, commissions, and transaction history.
</p>
<p>
The internal seller wallet and transaction balances used within the system are
LokalCraft platform records. During system evaluation, these records do not
represent a separate bank account, external electronic wallet, or guaranteed
withdrawable balance.
</p>
<p>
Sellers must not attempt to manipulate, falsify, or interfere with wallet,
commission, payment, or transaction records.
</p>
<h3>17. Cash Transactions</h3>
<p>
For Cash on Meetup or Pickup, the buyer and seller are responsible for completing
the physical cash exchange according to their confirmed arrangement.
</p>
<p>
The LokalCraft internal wallet does not represent the physical cash exchanged
between the buyer and seller. Its role in a cash transaction is limited to the
platform transaction-fee workflow implemented by the system.
</p>
<h3>18. Reviews and Ratings</h3>
<p>
Sellers may receive buyer reviews and ratings for completed orders.
Sellers must not threaten, harass, pressure, or improperly influence buyers in an
attempt to control the content of a review or rating.
</p>
<p>
Sellers may use legitimate customer feedback to improve product quality and service.
</p>
<h3>19. Prohibited Seller Activities</h3>
<p>
Sellers must not engage in activities that compromise the safety, integrity, or
accuracy of LokalCraft. Prohibited activities include:
</p>
<ul>
    <li>Using false identities or fraudulent business information;</li>
    <li>Submitting forged or manipulated verification documents;</li>
    <li>Creating false, deceptive, or misleading product listings;</li>
    <li>Listing counterfeit, prohibited, harmful, or illegal products;</li>
    <li>Manipulating product stock, prices, orders, payment records, reviews, commissions, or internal wallet records;</li>
    <li>Falsely marking an order as paid, processed, completed, cancelled, or otherwise changing its status dishonestly;</li>
    <li>Using LokalCraft for fraud, scams, harassment, threats, or other unlawful activity;</li>
    <li>Attempting to access administrator-only functions, another user's account, or restricted platform data without authorization;</li>
    <li>Uploading malicious files, harmful code, or content designed to disrupt the platform.</li>
</ul>
<h3>20. Administrator Monitoring and Enforcement</h3>
<p>
Authorized LokalCraft administrators may review seller applications, verification
records, product listings, orders, payment status, platform commission records,
and other information necessary for legitimate platform administration.
</p>
<p>
The Administrator may approve or reject seller applications and product listings
and may take appropriate action when a seller violates marketplace requirements
or this Seller Agreement.
</p>
<p>
Depending on the violation, actions may include listing removal, access restriction,
seller suspension, or account termination.
</p>
<h3>21. Seller Responsibility for Fulfillment</h3>
<p>
Sellers are responsible for carrying out the final arrangement they confirmed with
the buyer, including the agreed product, quantity, customization, price, fulfillment
method, location, date, and time.
</p>
<p>
If an order cannot be fulfilled, the seller should use the applicable order controls
and communicate the situation to the buyer through LokalCraft.
</p>
<h3>22. Platform Limitations</h3>
<p>
Sellers acknowledge that LokalCraft does not provide real-time courier tracking,
automated logistics management, card-payment processing, external seller payout,
or guaranteed withdrawal services unless such functions are specifically implemented
and made available by the platform.
</p>
<p>
Digital-payment and internal-wallet functions used during system evaluation operate
within LokalCraft's configured testing environment. Sellers must not represent test
or internal system records as actual external funds.
</p>
<h3>23. Changes to this Seller Agreement</h3>
<p>
LokalCraft may update this Seller Agreement when platform features, seller
requirements, transaction processes, or marketplace policies change.
</p>
<p>
Material changes should be presented through the platform. Continued use of seller
features after an applicable update indicates acceptance of the updated Seller Agreement.
</p>
<h3>24. Seller Acknowledgment</h3>
<p>
By continuing the seller registration process, submitting a seller application,
and using LokalCraft seller functions, you acknowledge that you have read,
understood, and agreed to this Seller Agreement.
</p>
<p>
You also acknowledge that your use of LokalCraft remains subject to the platform's
Terms and Conditions and Privacy Policy.
</p>
