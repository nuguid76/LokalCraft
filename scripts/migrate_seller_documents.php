<?php
if (PHP_SAPI !== 'cli') { http_response_code(403); exit('Forbidden'); }
require_once __DIR__ . '/../config/database.php';
require_once __DIR__ . '/../config/private_storage.php';
$legacyRoot = dirname(__DIR__) . '/uploads/seller_documents';
$targetRoot = LOKALCRAFT_SELLER_DOCUMENT_ROOT;
if (!is_dir($targetRoot) && !mkdir($targetRoot, 0700, true)) {
    exit("Cannot create private document folder.\n");
}
$rows = $conn->query('SELECT business_id, validid, businesspermit FROM businessinfo');
$updated = 0; $skipped = 0; $oldFiles = [];
while ($row = $rows->fetch_assoc()) {
    $replacements = [];
    $fresh = [];
    $sources = [];
    try {
        foreach (['validid', 'businesspermit'] as $field) {
            $value = (string) ($row[$field] ?? '');
            if (preg_match('/\A[a-f0-9]{32}\.(?:pdf|jpg|png|webp)\z/D', $value)) {
                if (!is_file($targetRoot . '/' . $value)) throw new RuntimeException('Private file missing: ' . $field);
                $replacements[$field] = $value;
                continue;
            }
            // Only files generated by LokalCraft's original uploader can be migrated.
            if (!preg_match('~\Auploads/seller_documents/([a-f0-9]{32}\.(?:pdf|jpg|png|webp))\z~D', $value, $m)) {
                throw new RuntimeException('Unsupported legacy path: ' . $field);
            }
            $name = $m[1];
            $source = $legacyRoot . '/' . $name;
            $target = $targetRoot . '/' . $name;
            if (!is_file($source)) throw new RuntimeException('Legacy file missing: ' . $field);
            if (is_file($target)) {
                if (!hash_equals(hash_file('sha256', $source), hash_file('sha256', $target))) {
                    throw new RuntimeException('Private filename collision: ' . $field);
                }
            } else {
                if (!copy($source, $target)) throw new RuntimeException('Cannot copy file: ' . $field);
                @chmod($target, 0600);
                $fresh[] = $target;
            }
            $replacements[$field] = $name;
            $sources[] = $source;
        }
        $conn->begin_transaction();
        $stmt = $conn->prepare('UPDATE businessinfo SET validid = ?, businesspermit = ? WHERE business_id = ? AND validid = ? AND businesspermit = ?');
        $originalId = (string) $row['validid'];
        $originalPermit = (string) $row['businesspermit'];
        $bid = (int) $row['business_id'];
        $stmt->bind_param('ssiss', $replacements['validid'], $replacements['businesspermit'], $bid, $originalId, $originalPermit);
        $stmt->execute();
        if ($stmt->affected_rows < 1 && ($originalId !== $replacements['validid'] || $originalPermit !== $replacements['businesspermit'])) throw new RuntimeException('Database record changed during migration.');
        $stmt->close();
        $conn->commit();
        $oldFiles = array_merge($oldFiles, $sources);
        $updated++;
        echo "Migrated business #{$bid}\n";
    } catch (Throwable $e) {
        try { $conn->rollback(); } catch (Throwable $ignored) {}
        foreach ($fresh as $file) if (is_file($file)) @unlink($file);
        $skipped++;
        echo 'Skipped business #' . $row['business_id'] . ': ' . $e->getMessage() . "\n";
    }
}
$rows->free();
echo "Updated: {$updated}; skipped: {$skipped}\n";
echo "Important: Once you verify all documents in the admin UI, DELETE the old public files in uploads/seller_documents.\n";
